    fun translate(labelEn: String): List<String> {
        val key = labelEn.trim().lowercase()
        return DICTIONARY[key] ?: emptyList()
    }

    fun translateAll(labelsEn: Collection<String>): List<String> {
        val result = LinkedHashSet<String>()
        for (label in labelsEn) {
            val translations = translate(label)
            if (translations.isNotEmpty()) {
                result.addAll(translations)
            } else {
                // If compound label (e.g. "Mountain range" or "Sports car"), try splitting
                val words = label.split(" ", "-", "_").filter { it.length > 2 }
                for (word in words) {
                    result.addAll(translate(word))
                }
            }
        }
        return result.toList()
    }
